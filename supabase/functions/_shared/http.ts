export const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-j-key, x-j-cron-key, x-j-feed-key",
  "Access-Control-Allow-Methods": "POST, GET, OPTIONS",
};
export function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), { status, headers: { ...corsHeaders, "Content-Type": "application/json" } });
}
export class HttpError extends Error { constructor(public status: number, message: string) { super(message); } }
export function fail(status: number, message: string): never { throw new HttpError(status, message); }
export async function readJson<T>(req: Request): Promise<T> {
  try { return (await req.json()) as T; } catch { fail(400, "Body must be JSON"); }
}
/** Wraps a handler: CORS preflight, uniform error responses. */
export function handler(fn: (req: Request) => Promise<Response>): (req: Request) => Promise<Response> {
  return async (req) => {
    if (req.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
    try { return await fn(req); }
    catch (e) {
      if (e instanceof HttpError) return json({ error: e.message }, e.status);
      console.error(e);
      return json({ error: e instanceof Error ? e.message : "Unexpected error" }, 500);
    }
  };
}
/** pg_cron calls carry x-j-cron-key. The key lives in private.config (generated by the migration); J_CRON_KEY env is an optional override. */
export async function isCronCall(req: Request): Promise<boolean> {
  const key = req.headers.get("x-j-cron-key") ?? "";
  if (!key) return false;
  const env = Deno.env.get("J_CRON_KEY");
  if (env && key === env) return true;
  const { serviceClient } = await import("./supabase.ts");
  const { data } = await serviceClient().rpc("cron_key_check", { p_key: key });
  return data === true;
}
export async function requireCronKey(req: Request): Promise<void> {
  if (!(await isCronCall(req))) fail(401, "Bad cron key");
}
